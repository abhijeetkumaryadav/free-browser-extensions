# ---------- Validate & emit words.js ----------
def clean(lst, name):
    seen, out, bad = set(), [], []
    for w in lst:
        w = w.strip().lower()
        if len(w) != 5 or not w.isalpha():
            bad.append(w); continue
        if w in seen: continue
        seen.add(w); out.append(w)
    print(f"{name}: {len(out)} unique valid (dropped: {bad})")
    return out

answers = clean(ANSWERS, "answers")
extra = clean(ALLOWED_EXTRA, "extra")
answers_set = set(answers)
extra = [w for w in extra if w not in answers_set]
allowed = sorted(set(answers) | set(extra))
print(f"extra (non-answer): {len(extra)}, total allowed: {len(allowed)}")
assert len(answers) >= 500, "need 500+ answers"
assert len(allowed) >= 1200, "need 1200+ allowed guesses"

with open("words.js", "w") as f:
    f.write("// Bundled word lists — generated from gen_words.py. No network needed.\n")
    f.write("const WORDLE_ANSWERS = " + __import__("json").dumps(answers) + ";\n")
    f.write("const WORDLE_ALLOWED = new Set(" + __import__("json").dumps(allowed) + ");\n")
print("wrote words.js")
