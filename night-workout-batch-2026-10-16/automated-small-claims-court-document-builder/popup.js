/* Small Claims Doc Builder — popup logic.
   Template text generation is pure string assembly; nothing here is legal advice. */

'use strict';

const $ = (id) => document.getElementById(id);
const FORM_KEY = 'scdb.form.v1';
const CHECK_KEY = 'scdb.checklist.v1';

const FIELDS = ['fYourName', 'fYourAddr', 'fTheirName', 'fTheirAddr', 'fFacts', 'fAmount', 'fDays', 'fEvidence'];

const CHECKLIST_ITEMS = [
  'Confirm your claim amount fits your state/court small-claims limit.',
  'Check the filing deadline (statute of limitations) for your claim type.',
  'Send the demand letter and keep proof of delivery.',
  'Download or pick up your court\'s official claim form.',
  'Fill in the defendant\'s exact legal name and address for service.',
  'File the claim and pay the filing fee; keep the stamped copy.',
  'Arrange proper service of process on the defendant (rules vary).',
  'Organize evidence: contracts, receipts, photos, messages — with dates.',
  'Prepare a one-page timeline of events to bring to the hearing.',
  'Confirm the hearing date, time, and courtroom; arrive early.',
];

/* ---------- storage ---------- */
async function loadForm() {
  const out = await chrome.storage.local.get(FORM_KEY);
  return out[FORM_KEY] || {};
}
async function saveForm(data) {
  await chrome.storage.local.set({ [FORM_KEY]: data });
}
async function loadCheck() {
  const out = await chrome.storage.local.get(CHECK_KEY);
  return Array.isArray(out[CHECK_KEY]) ? out[CHECK_KEY] : [];
}
async function saveCheck(done) {
  await chrome.storage.local.set({ [CHECK_KEY]: done });
}

function getData() {
  const data = {};
  for (const f of FIELDS) data[f] = $(f).value.trim();
  return data;
}
const money = (n) => '$' + Number(n).toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const todayStr = () => new Date().toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' });

/* ---------- pure document builders (unit-testable) ---------- */
function buildLetter(d) {
  const yn = d.fYourName || '[Your Full Name]';
  const ya = d.fYourAddr || '[Your Address]';
  const tn = d.fTheirName || '[Other Party\'s Name]';
  const ta = d.fTheirAddr || '[Other Party\'s Address]';
  const facts = d.fFacts || '[Describe what happened, with dates and amounts.]';
  const amt = d.fAmount ? money(parseFloat(d.fAmount)) : '[Amount]';
  const days = d.fDays || '14';
  return (
`${yn}
${ya}

${todayStr()}

${tn}
${ta}

Re: Demand for payment of ${amt}

Dear ${tn},

I am writing to resolve the following matter before taking further steps:

${facts}

Because of the above, I am owed ${amt}. Please pay this amount in full within ${days} days of the date of this letter.

If I do not receive payment (or a written payment agreement) by then, I intend to file a claim in small claims court, where I will ask for the amount above plus any filing fees and costs the court allows.

Please contact me at your earliest convenience to resolve this.

Sincerely,

${yn}

---
Template generated by Small Claims Doc Builder. This is NOT legal advice.
Verify your local court's rules, limits, and deadlines.`
  );
}

function buildOutline(d) {
  const tn = d.fTheirName || '[Other Party\'s Name]';
  const facts = d.fFacts || '[Describe what happened, with dates and amounts.]';
  const amt = d.fAmount ? money(parseFloat(d.fAmount)) : '[Amount]';
  const evidence = (d.fEvidence || '')
    .split('\n').map((l) => l.trim()).filter(Boolean);
  const evBlock = evidence.length
    ? evidence.map((e, i) => `   ${i + 1}. ${e}`).join('\n')
    : '   [List each piece of evidence with its date.]';
  return (
`SMALL CLAIMS OUTLINE (template — not legal advice)

1. PARTIES
   Claimant: ${(d.fYourName || '[Your Full Name]')}, ${(d.fYourAddr || '[Your Address]')}
   Defendant: ${tn}, ${(d.fTheirAddr || '[Other Party\'s Address]')}

2. AMOUNT CLAIMED
   ${amt}

3. STATEMENT OF FACTS
   ${facts}

4. WHY THE DEFENDANT OWES THIS
   [In one or two sentences, state the basis: unpaid invoice, deposit not
   returned, faulty work, broken agreement, etc.]

5. EVIDENCE TO BRING
${evBlock}

6. DAMAGES BREAKDOWN
   [List each cost: e.g. principal ${amt}, filing fee, service fee.]

7. WHAT YOU ARE ASKING THE COURT TO DO
   Order the defendant to pay ${amt} plus allowable costs.

---
Template generated by Small Claims Doc Builder. This is NOT legal advice.
Verify your local court's rules, limits, and deadlines.`
  );
}

/* ---------- rendering ---------- */
function renderDocs(data) {
  $('letterOut').textContent = buildLetter(data);
  $('outlineOut').textContent = buildOutline(data);
}

function renderChecklist(done) {
  const ul = $('checklist');
  ul.innerHTML = '';
  CHECKLIST_ITEMS.forEach((text, i) => {
    const li = document.createElement('li');
    if (done.includes(i)) li.classList.add('done');
    const box = document.createElement('span');
    box.className = 'c-box';
    box.textContent = done.includes(i) ? '✓' : '';
    const span = document.createElement('span');
    span.className = 'c-text';
    span.textContent = text;
    li.appendChild(box); li.appendChild(span);
    li.addEventListener('click', async () => {
      const cur = await loadCheck();
      const next = cur.includes(i) ? cur.filter((x) => x !== i) : [...cur, i];
      await saveCheck(next);
      renderChecklist(next);
    });
    ul.appendChild(li);
  });
}

function copyText(text, btn) {
  navigator.clipboard.writeText(text).then(() => {
    const old = btn.textContent;
    btn.textContent = 'Copied!';
    setTimeout(() => { btn.textContent = old; }, 1500);
  }).catch(() => {
    btn.textContent = 'Copy failed';
    setTimeout(() => { btn.textContent = 'Copy text'; }, 1500);
  });
}

/* ---------- events ---------- */
document.addEventListener('DOMContentLoaded', async () => {
  // Restore saved form
  const saved = await loadForm();
  for (const f of FIELDS) if (saved[f] != null) $(f).value = saved[f];
  renderDocs(getData());
  renderChecklist(await loadCheck());

  // Tab switching
  document.querySelectorAll('.tab').forEach((tab) => {
    tab.addEventListener('click', () => {
      document.querySelectorAll('.tab').forEach((t) => t.classList.remove('active'));
      document.querySelectorAll('.view').forEach((v) => v.classList.remove('active'));
      tab.classList.add('active');
      $('view-' + tab.dataset.view).classList.add('active');
    });
  });

  // Generate: save + render
  $('generateBtn').addEventListener('click', async () => {
    const data = getData();
    await saveForm(data);
    renderDocs(data);
    // jump to letter view
    document.querySelectorAll('.tab').forEach((t) => t.classList.remove('active'));
    document.querySelectorAll('.view').forEach((v) => v.classList.remove('active'));
    document.querySelector('[data-view="letter"]').classList.add('active');
    $('view-letter').classList.add('active');
  });

  // Live-update docs while typing (debounced)
  let t = null;
  for (const f of FIELDS) {
    $(f).addEventListener('input', () => {
      clearTimeout(t);
      t = setTimeout(async () => {
        const data = getData();
        await saveForm(data);
        renderDocs(data);
      }, 400);
    });
  }

  $('copyLetter').addEventListener('click', (e) => copyText($('letterOut').textContent, e.currentTarget));
  $('copyOutline').addEventListener('click', (e) => copyText($('outlineOut').textContent, e.currentTarget));

  $('resetChecklist').addEventListener('click', async () => {
    await saveCheck([]);
    renderChecklist([]);
  });

  $('clearBtn').addEventListener('click', async () => {
    if (!confirm('Clear all saved form data?')) return;
    for (const f of FIELDS) $(f).value = '';
    if ($('fDays')) $('fDays').value = '14';
    await saveForm({});
    renderDocs(getData());
  });
});
